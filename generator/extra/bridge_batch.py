def _grid_rows(rnd, n, m, wall_p):
    """n 行 m 列的 01 网格文本。"""
    lines = []
    for _ in range(n):
        line = ""
        for _ in range(m):
            line += "1" if rnd.random() < wall_p else "0"
        lines.append(line)
    return "".join(ln + "\n" for ln in lines)


def _carved_maze(rnd, n, m, wall_p):
    """随机 01 网格，再沿一条只向右 / 向下的路线把沿途清成通路，
    保证右下角一定走得到 —— 大随机点考的是真的广度优先，不是一眼看出了不通。"""
    rows = [[1 if rnd.random() < wall_p else 0 for _ in range(m)] for _ in range(n)]
    i = j = 0
    rows[i][j] = 0
    while i < n - 1 or j < m - 1:
        if i == n - 1:
            j += 1
        elif j == m - 1:
            i += 1
        elif rnd.random() < 0.5:
            i += 1
        else:
            j += 1
        rows[i][j] = 0
    return "".join("".join(str(v) for v in row) + "\n" for row in rows)


def _ints(rnd, n, lo, hi):
    return [rnd.randint(lo, hi) for _ in range(n)]


